"""Demo script texts (explanation with the catalyst mistake, and the correction)."""

DEMO_EXPLANATION = (
    "A reversible reaction reaches equilibrium when the forward and the reverse reaction go at the same rate: "
    "it doesn't stop, because both reactions keep going, but the concentrations stay constant. "
    "Le Châtelier's principle says that if I disturb an equilibrium, the system shifts to counteract the disturbance: "
    "for example, if I add N2 to the ammonia synthesis, the equilibrium shifts towards NH3 to consume part of the "
    "added N2. The catalyst also shifts the equilibrium towards the products, which is why industry uses it "
    "to get more ammonia."
)

DEMO_FIX = (
    "The catalyst does not shift the equilibrium, because it speeds up the forward and the reverse reaction "
    "equally: equilibrium is reached sooner, but the amount of NH3 is the same. Industry uses it to save time, "
    "not to get more ammonia."
)
